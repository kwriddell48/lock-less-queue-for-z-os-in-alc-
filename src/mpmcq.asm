         XR    R0,R0  CLEAR REGISTER
         ST    R0,NODE_CNT_INT-MPMCQ_NODE(R3)  STORE INLINE FLAG
*  STORE 64-BIT ADDRESS
         STG   R0,NODE_PAYLOAD64-MPMCQ_NODE(R3)  STORE 64-BIT ORIGIN
         ST    R0,NODE_PAYLOAD_LEN-MPMCQ_NODE(R3)  STORE PAYLOAD LENGTH
         LR    R11,R9  COPY REGISTER
         LR    R5,R7  COPY REGISTER
