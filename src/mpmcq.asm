*PROCESS RENT,MACHINE(Z15)
         TITLE 'MPMCQ - LOCK-FREE MPMC FIFO'
***********************************************************************
*  MPMCQ  AMODE 31, STANDARD OS LINKAGE.
*  QINIT RETURNS 12 UNLESS THE QCB IS 256-BYTE ALIGNED.
*  NODE CELLS AND 31-BIT SLABS ARE GETMAIN'D AND NEVER FREEMAIN'D.
*  THE TASK THAT OBTAINED A CELL MUST OUTLIVE EVERY USER OF IT.
*  QENQ AND QDEQ USE THE CALLER SAVE AREA. NO GETMAIN ON THAT PATH
*  EXCEPT A COLD NODE OR A COLD SLAB. PAYGET/PAYFREE RUN WITH R13
*  AIMED AT THE OWNED NODE'S INLINE AREA (72 BYTES, OWN CACHE LINE).
*  EACH ENTRY SETS R12 TO ITS OWN LABEL. ONE BASE CANNOT COVER
*  A LATER ENTRY IF R15 IS THAT ENTRY RATHER THAN THE CSECT.
*  HEAD, TAIL, AND FREE ARE LOADED WITH LG. CDS COMPARES THAT
*  PAIR. HIGH HALVES ARE ZERO. A FAILED CDS RELOADS THE PAIR.
*  PAYLOADS UP TO NODE_INLINE_MAX SIT IN THE NODE. UP TO PAY31_MAX
*  COME FROM A SIZE-CLASS POOL. LARGER ONES USE IARV64.
*  AFTER LAAL ON ENQ_SEQ, POST THE NOTIFIER ECB IF A CALLBACK
*  WAS REQUESTED. NO ARMED FLAG AND NO BCR 15,0 FENCE.
*  NO TBEGIN: MVCL, POST, AND GETMAIN STAY OUTSIDE ANY TX.
***********************************************************************
         PRINT GEN
         COPY  REGS
         COPY  DSECTS
         COPY  API
         COPY  ATOMICS
         COPY  COPY64
         COPY  LINKAGE
*
MPMCQ    CSECT
MPMCQ    AMODE 31
MPMCQ    RMODE ANY
         USING MPMCQ,R12
         USING MPMCQ_QCB,R2
*
         ENTRY QINIT
         ENTRY QENQ
         ENTRY QDEQ
         EXTRN MPMCQ_POPFAST
         EXTRN MPMCQ_PSHFAST
         EXTRN MPMCQ_PUSHGLOB
         EXTRN MPMCQ_PAYGET
         EXTRN MPMCQ_PAYFREE
         EXTRN MPMCQ_NSTART
*
QINIT    QENTER MPMCQ  SAVE REGS AND SET BASE
*  LOAD QCB ADDRESS
         L     R2,QINIT_QCBADDR-MPMCQ_QINIT_PLIST(R11)
         LTR   R2,R2  COMPARE OR TEST
         JZ    QINIT12  BRANCH IF ZERO
         LR    R3,R2  COPY REGISTER
         NILF  R3,X'000000FF'  MASK BITS
         JNZ   QINIT12  BRANCH IF NOT ZERO
         ST    R11,0(R13)  KEEP PLIST POINTER
         LR    R0,R2  COPY REGISTER
         LHI   R1,QCB_SIZE  QCB LENGTH
         XR    R14,R14  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         MVC   QCB_EYECATCH,=CL8'MPMCQCB '  SET EYE CATCHER
         LHI   R0,MPMCQ_STATS_VERSION  STATS VERSION
         ST    R0,QCB_VERSION  STORE HEADER FIELD
*  LOAD CALLBACK ENTRY
         L     R3,QINIT_CB_EP-MPMCQ_QINIT_PLIST(R11)
         ST    R3,QCB_CB_EP  STORE NOTIFIER FIELD
*  LOAD CALLBACK CONTEXT
         L     R3,QINIT_CB_CTX-MPMCQ_QINIT_PLIST(R11)
         ST    R3,QCB_CB_CTX  STORE NOTIFIER FIELD
         L     R3,QINIT_USER_ECB-MPMCQ_QINIT_PLIST(R11)  LOAD USER ECB
         ST    R3,QCB_USER_ECB  STORE USER ECB
*  LOAD INITIAL NODE COUNT
         L     R3,QINIT_INITPOOL-MPMCQ_QINIT_PLIST(R11)
         LTR   R3,R3  COMPARE OR TEST
         JZ    QITLS  BRANCH IF ZERO
         CLFI  R3,X'0007FFFF'  COMPARE OR TEST
         JH    QINIT8  BRANCH IF HIGH
QITLS    DS    0H
         LHI   R0,16384  TLS TABLE LENGTH
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R5,R1  COPY REGISTER
         ST    R5,QCB_TLS  STORE SLOT TABLE
         LR    R0,R5  COPY REGISTER
         LHI   R1,16384  TLS TABLE LENGTH
         XR    R14,R14  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         LTR   R3,R3  COMPARE OR TEST
         JZ    QIDUMMY  BRANCH IF ZERO
         LR    R0,R3  COPY REGISTER
         MHI   R0,NODE_SIZE  BYTES FOR THE NODE POOL
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R5,R1  COPY REGISTER
         LR    R6,R3  COPY REGISTER
QIPOOL   DS    0H
         L     R15,=V(MPMCQ_PUSHGLOB)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         AHI   R5,NODE_SIZE  STEP TO NEXT NODE
         BCT   R6,QIPOOL  DECREMENT AND LOOP
         L     R11,0(R13)  RELOAD SAVED PLIST
*  LOAD QCB ADDRESS
         L     R2,QINIT_QCBADDR-MPMCQ_QINIT_PLIST(R11)
QIDUMMY  DS    0H
         LHI   R0,NODE_SIZE  NODE LENGTH
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R5,R1  COPY REGISTER
         L     R11,0(R13)  RELOAD SAVED PLIST
*  LOAD QCB ADDRESS
         L     R2,QINIT_QCBADDR-MPMCQ_QINIT_PLIST(R11)
         LR    R0,R5  COPY REGISTER
         LHI   R1,NODE_SIZE  NODE LENGTH
         XR    R14,R14  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         ST    R5,QCB_HEAD_PTR  STORE HEAD POINTER
         ST    R5,QCB_TAIL_PTR  STORE TAIL POINTER
         L     R15,=V(MPMCQ_NSTART)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         LTR   R15,R15  COMPARE OR TEST
         JZ    QINIT0  BRANCH IF ZERO
         J     QINITRET  BRANCH
QINIT12  DS    0H
         LHI   R15,RC_ALIGN  SET RETURN CODE
         J     QINITRET  BRANCH
QINIT8   DS    0H
         LHI   R15,RC_ALLOC  SET RETURN CODE
         J     QINITRET  BRANCH
QINIT0   DS    0H
         XR    R15,R15  CLEAR REGISTER
QINITRET DS    0H
         QLEAVE  FREE SAVE AREA AND RETURN
         LTORG
         DROP  R12
*
QENQ     STM   R14,R12,12(R13)  SAVE CALLER REGISTERS
         LARL  R12,QENQ  LOAD RELATIVE ADDRESS
         USING QENQ,R12
         L     R11,24(R13)  LOAD FULLWORD
         L     R2,ENQ_QCBADDR-MPMCQ_QENQ_PLIST(R11)  LOAD QCB ADDRESS
*  LOAD SOURCE ADDRESS
         L     R6,ENQ_SRCADDR-MPMCQ_QENQ_PLIST(R11)
         L     R7,ENQ_SRCLEN-MPMCQ_QENQ_PLIST(R11)  LOAD SOURCE LENGTH
         CLFI  R7,PAY64_MAX  COMPARE OR TEST
         JNH   QENQLEN  BRANCH IF NOT HIGH
         LHI   R15,RC_ALLOC  SET RETURN CODE
         J     QENQRET  BRANCH
QENQLEN  DS    0H
         L     R15,=V(MPMCQ_POPFAST)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         LTR   R1,R1  COMPARE OR TEST
         JNZ   QENQNOD  BRANCH IF NOT ZERO
         LHI   R0,NODE_SIZE  NODE LENGTH
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R5,R1  COPY REGISTER
         LR    R0,R5  COPY REGISTER
         LHI   R1,NODE_SIZE  NODE LENGTH
         XR    R14,R14  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         J     QENQGEN  BRANCH
QENQNOD  DS    0H
         LR    R5,R1  COPY REGISTER
QENQGEN  DS    0H
         L     R0,NODE_CNT_EXT-MPMCQ_NODE(R5)  LOAD NODE GENERATION
         ALFI  R0,1  ADD ONE TO ABA
         ST    R0,NODE_CNT_EXT-MPMCQ_NODE(R5)  STORE NODE GENERATION
         ST    R0,NODE_NEXT_ABA-MPMCQ_NODE(R5)  STORE NEXT ABA TAG
         XR    R1,R1  CLEAR REGISTER
         ST    R1,NODE_NEXT_PTR-MPMCQ_NODE(R5)  STORE NEXT POINTER
         ST    R1,NODE_CNT_INT-MPMCQ_NODE(R5)  STORE INLINE FLAG
*  STORE 64-BIT ADDRESS
         STG   R1,NODE_PAYLOAD64-MPMCQ_NODE(R5)  CLEAR 64-BIT ADDRESS
         ST    R1,NODE_PAYLOAD_LEN-MPMCQ_NODE(R5)  STORE PAYLOAD LENGTH
         LA    R0,NODE_INLINE-MPMCQ_NODE(R5)  ADDRESS INLINE AREA
         LHI   R1,NODE_INLINE_MAX  NODE LENGTH
         XR    R14,R14  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         LTR   R7,R7  COMPARE OR TEST
         JZ    QENQLINK  BRANCH IF ZERO
         CLFI  R7,NODE_INLINE_MAX  COMPARE OR TEST
         JH    QENQ64  BRANCH IF HIGH
         LA    R8,NODE_INLINE-MPMCQ_NODE(R5)  ADDRESS INLINE AREA
         LR    R0,R8  COPY REGISTER
         LR    R1,R7  COPY REGISTER
         LR    R14,R6  COPY REGISTER
         LR    R15,R7  COPY REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         LHI   R0,NODE_F_INLINE  NODE LENGTH
         ST    R0,NODE_CNT_INT-MPMCQ_NODE(R5)  STORE INLINE FLAG
         ST    R7,NODE_PAYLOAD_LEN-MPMCQ_NODE(R5)  STORE PAYLOAD LENGTH
         J     QENQSTAT  BRANCH
QENQ64   DS    0H
         LA    R4,NODE_INLINE-MPMCQ_NODE(R5)  ADDRESS INLINE AREA
         ST    R13,4(R4)  CHAIN SAVE AREA
         LR    R13,R4  COPY REGISTER
         L     R15,=V(MPMCQ_PAYGET)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         L     R13,4(R13)  LOAD FULLWORD
         LTR   R15,R15  COMPARE OR TEST
         JZ    QENQCPY  BRANCH IF ZERO
*  COUNT ALLOC FAILURE
         MPMCQ_STATINC R2,QCB_STAT_ENQ_ALLOC_FAIL,R8,R9
         L     R15,=V(MPMCQ_PSHFAST)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         LHI   R15,RC_ALLOC  SET RETURN CODE
         J     QENQRET  BRANCH
QENQCPY  DS    0H
         LLGFR R8,R8  KEEP LOW 32 BITS
         SLLG  R8,R8,32  SHIFT HALF TO HIGH
         LLGFR R9,R9  KEEP LOW 32 BITS
         ALGR  R8,R9  ADD REGISTERS
*  STORE 64-BIT ADDRESS
         STG   R8,NODE_PAYLOAD64-MPMCQ_NODE(R5)  CLEAR 64-BIT ADDRESS
         ST    R7,NODE_PAYLOAD_LEN-MPMCQ_NODE(R5)  STORE PAYLOAD LENGTH
         MPMCQ_COPY_31_TO_64 R6,R8,R7,R0,R10  COPY BYTES INTO PAYLOAD
QENQSTAT DS    0H
*  ADD PAYLOAD BYTES
         MPMCQ_STATADD64 R2,QCB_STAT_PAYLOAD64_CUR_HI,R7,R0,R8
         ALGR  R8,R0  NEW BYTE TOTAL
         LLGFR R7,R8  LOW HALF, HIGH BITS ZERO
         SRLG  R6,R8,32  HIGH HALF OF BYTE TOTAL
*  RAISE BYTE HIGH-WATER
         MPMCQ_STATMAX64 R2,QCB_STAT_PAYLOAD64_MAX_HI,R6,R7,R0,R8
QENQLINK DS    0H
         LG    R0,QCB_TAIL_ABA  LOAD TAIL ABA AND PTR
QENQHAVE DS    0H
         MPMCQ_STATINC R2,QCB_STAT_ENQ_RETRY,R8,R9  COUNT ENQUEUE RETRY
         LR    R1,R0  COPY REGISTER
         LTR   R1,R1  COMPARE OR TEST
         JZ    QENQBAD  BRANCH IF ZERO
         LG    R6,NODE_NEXT_ABA-MPMCQ_NODE(R1)  LOAD NEXT ABA AND PTR
QENQNEXT DS    0H
         LG    R8,QCB_TAIL_ABA  LOAD TAIL ABA AND PTR
         CGR   R8,R0  COMPARE OR TEST
         JE    QENQST  BRANCH IF EQUAL
         LGR   R0,R8  COPY REGISTER
         J     QENQHAVE  BRANCH
QENQST   DS    0H
         LR    R9,R6  COPY REGISTER
         LTR   R9,R9  COMPARE OR TEST
         JNZ   QENQHELP  BRANCH IF NOT ZERO
         LR    R9,R6  COPY REGISTER
         SRLG  R8,R6,32  SHIFT ABA TO LOW HALF
         LR    R10,R8  COPY REGISTER
         ALFI  R10,1  ADD ONE TO ABA
         LR    R11,R5  COPY REGISTER
*  COMPARE AND SWAP PAIR
         CDS   R8,R10,NODE_NEXT_ABA-MPMCQ_NODE(R1)
         JE    QENQSW  BRANCH IF EQUAL
         SLLG  R8,R8,32  SHIFT HALF TO HIGH
         LLGFR R9,R9  KEEP LOW 32 BITS
         ALGR  R8,R9  ADD REGISTERS
         LGR   R6,R8  COPY REGISTER
         MPMCQ_STATINC R2,QCB_STAT_ENQ_RETRY,R8,R9  COUNT ENQUEUE RETRY
         J     QENQNEXT  BRANCH
QENQSW   DS    0H
         LR    R9,R0  COPY REGISTER
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         LR    R10,R8  COPY REGISTER
         ALFI  R10,1  ADD ONE TO ABA
         LR    R11,R5  COPY REGISTER
         CDS   R8,R10,QCB_TAIL_ABA  COMPARE AND SWAP PAIR
         J     QENQPOST  BRANCH
QENQHELP DS    0H
         LR    R9,R0  COPY REGISTER
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         LR    R10,R8  COPY REGISTER
         ALFI  R10,1  ADD ONE TO ABA
         LR    R11,R6  COPY REGISTER
         CDS   R8,R10,QCB_TAIL_ABA  COMPARE AND SWAP PAIR
         JE    QENQHOK  BRANCH IF EQUAL
         SLLG  R8,R8,32  SHIFT HALF TO HIGH
         LLGFR R9,R9  KEEP LOW 32 BITS
         ALGR  R8,R9  ADD REGISTERS
         LGR   R0,R8  COPY REGISTER
         J     QENQHAVE  BRANCH
QENQHOK  DS    0H
         SLLG  R10,R10,32  SHIFT HALF TO HIGH
         LLGFR R11,R11  KEEP LOW 32 BITS
         ALGR  R10,R11  ADD REGISTERS
         LGR   R0,R10  COPY REGISTER
         J     QENQHAVE  BRANCH
QENQBAD  DS    0H
         L     R0,NODE_CNT_INT-MPMCQ_NODE(R5)  LOAD INLINE FLAG
         CLFI  R0,NODE_F_INLINE  COMPARE OR TEST
         JE    QENQBADP  BRANCH IF EQUAL
         L     R7,NODE_PAYLOAD_LEN-MPMCQ_NODE(R5)  LOAD PAYLOAD LENGTH
         LTR   R7,R7  COMPARE OR TEST
         JZ    QENQBADP  BRANCH IF ZERO
         LA    R1,NODE_PAYLOAD64-MPMCQ_NODE(R5)  ADDRESS PAYLOAD WORD
         LA    R4,NODE_INLINE-MPMCQ_NODE(R5)  ADDRESS INLINE AREA
         ST    R13,4(R4)  CHAIN SAVE AREA
         LR    R13,R4  COPY REGISTER
         L     R15,=V(MPMCQ_PAYFREE)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         L     R13,4(R13)  LOAD FULLWORD
QENQBADP DS    0H
         L     R15,=V(MPMCQ_PSHFAST)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
*  COUNT ALLOC FAILURE
         MPMCQ_STATINC R2,QCB_STAT_ENQ_ALLOC_FAIL,R8,R9
         LHI   R15,RC_ALLOC  SET RETURN CODE
         J     QENQRET  BRANCH
QENQPOST DS    0H
*  COUNT SUCCESSFUL ENQUEUE
         MPMCQ_STATINC R2,QCB_STAT_ENQ_OK,R8,R9
         LHI   R9,1  PLUS ONE
         LAAL  R8,R9,QCB_STAT_QDEPTH_CUR  ADJUST QUEUE DEPTH
         ALR   R9,R8  ADD REGISTERS
*  RAISE DEPTH HIGH-WATER
         MPMCQ_STATMAX R2,QCB_STAT_QDEPTH_MAX,R9,R8,R0
         LHI   R3,1  PLUS ONE
         LAAL  R0,R3,QCB_ENQ_SEQ  BUMP ENQUEUE SEQUENCE
         L     R4,QCB_CB_EP  LOAD CALLBACK ENTRY
         LTR   R4,R4  COMPARE OR TEST
         JZ    QENQUSR  BRANCH IF ZERO
         POST  QCB_CB_ECB  WAKE A WAITER
*  COUNT NOTIFIER POST
         MPMCQ_STATINC R2,QCB_STAT_POST_INTERNAL,R8,R9
QENQUSR  DS    0H
         L     R4,QCB_USER_ECB  LOAD USER ECB
         LTR   R4,R4  COMPARE OR TEST
         JZ    QENQOK  BRANCH IF ZERO
         POST  0(R4)  WAKE A WAITER
*  COUNT USER ECB POST
         MPMCQ_STATINC R2,QCB_STAT_POST_USERECB,R8,R9
QENQOK   DS    0H
         XR    R15,R15  CLEAR REGISTER
QENQRET  DS    0H
         L     R14,12(R13)  LOAD FULLWORD
         LM    R2,R12,28(R13)  RESTORE CALLER REGISTERS
         BR    R14  RETURN TO CALLER
         LTORG
         DROP  R12
*
QDEQ     STM   R14,R12,12(R13)  SAVE CALLER REGISTERS
         LARL  R12,QDEQ  LOAD RELATIVE ADDRESS
         USING QDEQ,R12
         L     R11,24(R13)  LOAD FULLWORD
         L     R2,DEQ_QCBADDR-MPMCQ_QDEQ_PLIST(R11)  LOAD QCB ADDRESS
         L     R6,DEQ_DSTADDR-MPMCQ_QDEQ_PLIST(R11)  LOAD DEST ADDRESS
         L     R7,DEQ_DSTMAX-MPMCQ_QDEQ_PLIST(R11)  LOAD DEST CAPACITY
*  LOAD OUTLEN ADDRESS
         L     R11,DEQ_OUTLENADDR-MPMCQ_QDEQ_PLIST(R11)
QDEQLOOP DS    0H
         LG    R0,QCB_HEAD_ABA  LOAD HEAD ABA AND PTR
QDEQHAVE DS    0H
         MPMCQ_STATINC R2,QCB_STAT_DEQ_RETRY,R8,R9  COUNT DEQUEUE RETRY
         LR    R5,R0  COPY REGISTER
         LTR   R5,R5  COMPARE OR TEST
         JZ    QDEQMT  BRANCH IF ZERO
         LG    R8,NODE_NEXT_ABA-MPMCQ_NODE(R5)  LOAD NEXT ABA AND PTR
         LG    R4,QCB_HEAD_ABA  LOAD HEAD ABA AND PTR
         CGR   R4,R0  COMPARE OR TEST
         JE    QDEQST  BRANCH IF EQUAL
         LGR   R0,R4  COPY REGISTER
         J     QDEQHAVE  BRANCH
QDEQST   DS    0H
         LR    R9,R8  COPY REGISTER
         LTR   R9,R9  COMPARE OR TEST
         JZ    QDEQMT  BRANCH IF ZERO
*        HEAD AND TAIL ON THE SAME NODE, WITH A SUCCESSOR: TAIL LAGS.
*        SWING TAIL TO THAT SUCCESSOR BEFORE THE DUMMY CAN BE FREED.
         LG    R4,QCB_TAIL_ABA  LOAD TAIL ABA AND PTR
         LR    R1,R4  COPY REGISTER
         CLR   R5,R1  COMPARE OR TEST
         JNE   QDEQSWING  BRANCH IF NOT EQUAL
         LR    R5,R4  TAIL NODE EQUALS HEAD NODE
         L     R9,NODE_NEXT_PTR-MPMCQ_NODE(R5)  NEXT PTR FOR NEW TAIL
         LTR   R9,R9  COMPARE OR TEST
         JZ    QDEQLOOP  BRANCH IF ZERO
         SRLG  R4,R4,32  SHIFT ABA TO LOW HALF
         LR    R8,R4  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         CDS   R4,R8,QCB_TAIL_ABA  SWING TAIL ONTO NEXT
         J     QDEQLOOP  BRANCH
QDEQSWING DS   0H
         LR    R3,R9  COPY REGISTER
         LR    R5,R0  COPY REGISTER
         SRLG  R4,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R4  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         LR    R9,R3  COPY REGISTER
         CDS   R4,R8,QCB_HEAD_ABA  COMPARE AND SWAP PAIR
         JE    QDEQWIN  BRANCH IF EQUAL
         SLLG  R4,R4,32  SHIFT HALF TO HIGH
         LLGFR R5,R5  KEEP LOW 32 BITS
         ALGR  R4,R5  ADD REGISTERS
         LGR   R0,R4  COPY REGISTER
         J     QDEQHAVE  BRANCH
QDEQWIN  DS    0H
         L     R8,NODE_PAYLOAD_LEN-MPMCQ_NODE(R3)  LOAD PAYLOAD LENGTH
         LTR   R11,R11  COMPARE OR TEST
         JZ    QDEQNOL  BRANCH IF ZERO
         ST    R8,0(R11)  STORE FULLWORD
QDEQNOL  DS    0H
         CLR   R8,R7  COMPARE OR TEST
         JH    QDEQTR  BRANCH IF HIGH
         LR    R0,R8  COPY REGISTER
         XR    R9,R9  CLEAR REGISTER
         J     QDEQSAV  BRANCH
QDEQTR   DS    0H
         LR    R0,R7  COPY REGISTER
         LHI   R9,RC_TRUNC  SET RETURN CODE
QDEQSAV  DS    0H
         LR    R7,R5  COPY REGISTER
         LTR   R0,R0  COMPARE OR TEST
         JZ    QDEQFR  BRANCH IF ZERO
         L     R1,NODE_CNT_INT-MPMCQ_NODE(R3)  LOAD INLINE FLAG
         CLFI  R1,NODE_F_INLINE  COMPARE OR TEST
         JE    QDEQIN  BRANCH IF EQUAL
*  LOAD 64-BIT PAYLOAD ADDR
         LG    R8,NODE_PAYLOAD64-MPMCQ_NODE(R3)
         MPMCQ_COPY_64_TO_31 R8,R6,R0,R4,R10  COPY PAYLOAD TO CALLER
         J     QDEQFR  BRANCH
QDEQIN   DS    0H
         LR    R1,R0  COPY REGISTER
         LR    R15,R0  COPY REGISTER
         LR    R0,R6  COPY REGISTER
         LA    R14,NODE_INLINE-MPMCQ_NODE(R3)  ADDRESS INLINE AREA
         MVCL  R0,R14  MOVE OR CLEAR BYTES
QDEQFR   DS    0H
         L     R1,NODE_CNT_INT-MPMCQ_NODE(R3)  LOAD INLINE FLAG
         CLFI  R1,NODE_F_INLINE  COMPARE OR TEST
         JE    QDEQSUB  BRANCH IF EQUAL
         L     R4,NODE_PAYLOAD_LEN-MPMCQ_NODE(R3)  LOAD PAYLOAD LENGTH
         LTR   R4,R4  COMPARE OR TEST
         JZ    QDEQCLR  BRANCH IF ZERO
         LR    R11,R7  COPY REGISTER
         LR    R7,R4  COPY REGISTER
         LA    R1,NODE_PAYLOAD64-MPMCQ_NODE(R3)  ADDRESS PAYLOAD WORD
         LA    R4,NODE_INLINE-MPMCQ_NODE(R3)  ADDRESS INLINE AREA
         ST    R13,4(R4)  CHAIN SAVE AREA
         LR    R13,R4  COPY REGISTER
         L     R15,=V(MPMCQ_PAYFREE)  LOAD ENTRY ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         L     R13,4(R13)  LOAD FULLWORD
         LR    R7,R11  COPY REGISTER
QDEQSUB  DS    0H
         L     R4,NODE_PAYLOAD_LEN-MPMCQ_NODE(R3)  LOAD PAYLOAD LENGTH
         LTR   R4,R4  COMPARE OR TEST
         JZ    QDEQCLR  BRANCH IF ZERO
         LR    R6,R4  COPY REGISTER
         LCR   R6,R6  NEGATE BYTE COUNT
*  SUBTRACT PAYLOAD BYTES
         MPMCQ_STATADD64S R2,QCB_STAT_PAYLOAD64_CUR_HI,R6,R0,R8
