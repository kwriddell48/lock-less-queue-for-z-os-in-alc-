*PROCESS RENT,MACHINE(Z15)
         TITLE 'MPMCQFL - NODE FREELIST'
***********************************************************************
*  MPMCQFL
*  IN_POPNODE / MPMCQ_POPNODE: STANDARD LINKAGE.
*  R1=0 EMPTY, R1=NODE OTHERWISE. R15 IS NOT THE EMPTY INDICATOR.
*  MPMCQ_POPFAST / MPMCQ_PSHFAST: LEAVES. NO SAVE-AREA USE.
*  PRESERVE R2,R5,R6,R7,R11,R12,R13. R4 IS THE SAVED RETURN.
*  CLOBBER R0,R1,R3,R4,R8,R9,R10,R14,R15.
*  POPFAST: R2=QCB, R1=NODE OR 0. PSHFAST: R2=QCB, R5=NODE.
*  EACH TCB KEEPS UP TO TLS_DEPTH NODES. PSATOLD SELECTS THE SLOT.
*  (OWNER,COUNT) IS ONE CDS WORD. ONLY A SLOT WHOSE COUNT IS 0
*  MAY BE CLAIMED. THE AGE CHECK USES SCRATCH AT THE END OF THE SLOT.
*  MPMCQ_PUSHGLOB UPDATES ONLY THE GLOBAL STACK (QINIT).
*  A FAILED CDS RELOADS THE PAIR. HIGH HALVES ARE ZERO SO SLLG
*  REBUILDS THE DOUBLEWORD. NO SECOND LG OF THAT SAME WORD.
***********************************************************************
         PRINT GEN
         COPY  REGS
         COPY  DSECTS
         COPY  ATOMICS
         COPY  LINKAGE
*
MPMCQFL  CSECT
MPMCQFL  AMODE 31
MPMCQFL  RMODE ANY
         USING MPMCQFL,R12
         USING MPMCQ_QCB,R2
*
         ENTRY IN_POPNODE
         ENTRY MPMCQ_POPNODE
         ENTRY MPMCQ_POPFAST
         ENTRY MPMCQ_PUSHNODE
         ENTRY MPMCQ_PSHFAST
         ENTRY MPMCQ_PUSHGLOB
*
IN_POPNODE       DS    0H
MPMCQ_POPNODE    DS    0H
         QLEAF MPMCQFL  SAVE REGS AND SET BASE
         LARL  R15,MPMCQ_POPFAST  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         QLEAVER  RESTORE REGS AND RETURN
*
MPMCQ_PUSHNODE   DS    0H
         QLEAF MPMCQFL  SAVE REGS AND SET BASE
         LARL  R15,MPMCQ_PSHFAST  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         QLEAVER  RESTORE REGS AND RETURN
*
MPMCQ_POPFAST    DS    0H
         LR    R4,R14  SAVE RETURN ADDRESS
         XR    R10,R10  CLEAR REGISTER
         L     R3,PSATOLD(0)  LOAD CURRENT TCB
         L     R1,QCB_TLS  LOAD SLOT TABLE
         LTR   R1,R1  COMPARE OR TEST
         JZ    POPFILL  BRANCH IF ZERO
         LR    R0,R3  COPY REGISTER
         SRL   R0,8  SHIFT TCB FOR HASH
         NILF  R0,63  HASH MASK 64 SLOTS
         SLL   R0,8  TIMES 256 FOR SLOT
         AR    R1,R0  ADD SLOT OFFSET
         LR    R10,R1  COPY REGISTER
POPCLAIM DS    0H
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JE    POPUSE  BRANCH IF EQUAL
         LR    R9,R0  COPY REGISTER
         LTR   R8,R8  COMPARE OR TEST
         JZ    POPDOCL  BRANCH IF ZERO
         LTR   R9,R9  COMPARE OR TEST
         JNZ   POPSKIP  BRANCH IF NOT ZERO
         STCK  TLS_LINE-8(R10)  SAMPLE TIME IN THIS SLOT
         JNE   POPSKIP  BRANCH IF NOT EQUAL
         LG    R8,TLS_LINE-8(R10)  LOAD SAMPLED TIME
*  LOAD LAST-USE STAMP
         LG    R14,TLS_STAMP(R10)  LOAD LAST-USE STAMP
         SLGR  R8,R14  ELAPSED TOD DELTA
         IILF  R14,X'F4240000'  ONE SECOND OF TOD
         CLGR  R8,R14  IS STAMP OLDER THAN 1S
         JL    POPSKIP  BRANCH IF LOW
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JE    POPUSE  BRANCH IF EQUAL
         LR    R9,R0  COPY REGISTER
         LTR   R9,R9  COMPARE OR TEST
         JNZ   POPSKIP  BRANCH IF NOT ZERO
POPDOCL  DS    0H
         XR    R1,R1  CLEAR REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R3  COPY REGISTER
         XR    R9,R9  CLEAR REGISTER
         CDS   R0,R8,TLS_OWNER(R10)  COMPARE AND SWAP PAIR
         JNE   POPSKIP  BRANCH IF NOT EQUAL
         STCK  TLS_STAMP(R10)  STAMP LAST USE OF SLOT
POPUSE   DS    0H
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JNE   POPCLAIM  BRANCH IF NOT EQUAL
         LR    R9,R0  COPY REGISTER
         LTR   R9,R9  COMPARE OR TEST
         JZ    POPFILL  BRANCH IF ZERO
         LR    R8,R9  COPY REGISTER
         AHI   R8,-1  COUNT MINUS ONE
         SLL   R8,2  TIMES 4 FOR INDEX
         L     R14,TLS_NODES(R10,R8)  LOAD FULLWORD
         LR    R1,R9  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R3  COPY REGISTER
         LR    R9,R1  COPY REGISTER
         AHI   R9,-1  COUNT MINUS ONE
         CDS   R0,R8,TLS_OWNER(R10)  COMPARE AND SWAP PAIR
         JNE   POPUSE  BRANCH IF NOT EQUAL
         STCK  TLS_STAMP(R10)  STAMP LAST USE OF SLOT
         LR    R1,R14  COPY REGISTER
         J     POPRET  BRANCH
POPSKIP  DS    0H
         XR    R10,R10  CLEAR REGISTER
POPFILL  DS    0H
         LARL  R15,POPGLOB  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         L     R3,PSATOLD(0)  LOAD CURRENT TCB
         LTR   R1,R1  COMPARE OR TEST
         JZ    POPRET0  BRANCH IF ZERO
         LTR   R10,R10  COMPARE OR TEST
         JZ    POPRET  BRANCH IF ZERO
POPFL2   DS    0H
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JNE   POPRET  BRANCH IF NOT EQUAL
         LR    R9,R0  COPY REGISTER
         CHI   R9,4  COMPARE OR TEST
         JNL   POPRET  BRANCH IF NOT LOW
         LR    R8,R9  COPY REGISTER
         SLL   R8,2  TIMES 4 FOR INDEX
         ST    R1,TLS_NODES(R10,R8)  STORE NODE IN SLOT
         LR    R14,R1  COPY REGISTER
         LR    R1,R9  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R3  COPY REGISTER
         LR    R9,R1  COPY REGISTER
         AHI   R9,1  COUNT PLUS ONE
         CDS   R0,R8,TLS_OWNER(R10)  COMPARE AND SWAP PAIR
         JNE   POPFLNO  BRANCH IF NOT EQUAL
         STCK  TLS_STAMP(R10)  STAMP LAST USE OF SLOT
         LARL  R15,POPGLOB  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         L     R3,PSATOLD(0)  LOAD CURRENT TCB
         LTR   R1,R1  COMPARE OR TEST
         JNZ   POPFL2  BRANCH IF NOT ZERO
         J     POPUSE  BRANCH
POPFLNO  DS    0H
         LR    R1,R14  COPY REGISTER
POPRET   DS    0H
         XR    R15,R15  CLEAR REGISTER
         LR    R14,R4  RESTORE RETURN ADDRESS
         BR    R14  RETURN TO CALLER
POPRET0  DS    0H
         XR    R1,R1  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         LR    R14,R4  RESTORE RETURN ADDRESS
         BR    R14  RETURN TO CALLER
*
* R2=QCB, R14=RETURN. R1=NODE OR 0. PRESERVES R4,R6,R7,R10,R11,R12.
POPGLOB  DS    0H
         LG    R0,QCB_FREE_ABA  LOAD FREELIST HEAD
POPGH    DS    0H
         LR    R1,R0  COPY REGISTER
         LTR   R1,R1  COMPARE OR TEST
         JZ    POPGE  BRANCH IF ZERO
         LG    R8,NODE_NEXT_ABA-MPMCQ_NODE(R1)  LOAD NEXT ABA AND PTR
         LG    R3,QCB_FREE_ABA  LOAD FREELIST HEAD
         CGR   R3,R0  COMPARE OR TEST
         JE    POPGS  BRANCH IF EQUAL
         LGR   R0,R3  COPY REGISTER
*  COUNT FREELIST POP RETRY
         MPMCQ_STATINC R2,QCB_STAT_FREELIST_POP_RETRY,R8,R9
         J     POPGH  BRANCH
POPGS    DS    0H
         LR    R9,R8  COPY REGISTER
         LR    R3,R1  COPY REGISTER
         LR    R1,R0  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R0  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         CDS   R0,R8,QCB_FREE_ABA  COMPARE AND SWAP PAIR
         JE    POPGK  BRANCH IF EQUAL
*  COUNT FREELIST POP RETRY
         MPMCQ_STATINC R2,QCB_STAT_FREELIST_POP_RETRY,R8,R9
         SLLG  R0,R0,32  SHIFT HALF TO HIGH
         LLGFR R1,R1  KEEP LOW 32 BITS
         ALGR  R0,R1  ADD REGISTERS
         J     POPGH  BRANCH
POPGK    DS    0H
         LR    R1,R3  COPY REGISTER
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
POPGE    DS    0H
         XR    R1,R1  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
*
MPMCQ_PSHFAST    DS    0H
         LR    R4,R14  SAVE RETURN ADDRESS
         L     R3,PSATOLD(0)  LOAD CURRENT TCB
         L     R1,QCB_TLS  LOAD SLOT TABLE
         LTR   R1,R1  COMPARE OR TEST
         JZ    PSHG  BRANCH IF ZERO
         LR    R0,R3  COPY REGISTER
         SRL   R0,8  SHIFT TCB FOR HASH
         NILF  R0,63  HASH MASK 64 SLOTS
         SLL   R0,8  TIMES 256 FOR SLOT
         AR    R1,R0  ADD SLOT OFFSET
         LR    R10,R1  COPY REGISTER
PSHCLAIM DS    0H
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JE    PSHUSE  BRANCH IF EQUAL
         LR    R9,R0  COPY REGISTER
         LTR   R8,R8  COMPARE OR TEST
         JZ    PSHDOCL  BRANCH IF ZERO
         LTR   R9,R9  COMPARE OR TEST
         JNZ   PSHG  BRANCH IF NOT ZERO
         STCK  TLS_LINE-8(R10)  SAMPLE TIME IN THIS SLOT
         JNE   PSHG  BRANCH IF NOT EQUAL
         LG    R8,TLS_LINE-8(R10)  LOAD SAMPLED TIME
*  LOAD LAST-USE STAMP
         LG    R14,TLS_STAMP(R10)  LOAD LAST-USE STAMP
         SLGR  R8,R14  ELAPSED TOD DELTA
         IILF  R14,X'F4240000'  ONE SECOND OF TOD
         CLGR  R8,R14  IS STAMP OLDER THAN 1S
         JL    PSHG  BRANCH IF LOW
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JE    PSHUSE  BRANCH IF EQUAL
         LR    R9,R0  COPY REGISTER
         LTR   R9,R9  COMPARE OR TEST
         JNZ   PSHG  BRANCH IF NOT ZERO
PSHDOCL  DS    0H
         XR    R1,R1  CLEAR REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R3  COPY REGISTER
         XR    R9,R9  CLEAR REGISTER
         CDS   R0,R8,TLS_OWNER(R10)  COMPARE AND SWAP PAIR
         JNE   PSHG  BRANCH IF NOT EQUAL
         STCK  TLS_STAMP(R10)  STAMP LAST USE OF SLOT
PSHUSE   DS    0H
         LG    R0,TLS_OWNER(R10)  LOAD OWNER AND COUNT
         SRLG  R8,R0,32  SHIFT ABA TO LOW HALF
         CLR   R8,R3  COMPARE OR TEST
         JNE   PSHCLAIM  BRANCH IF NOT EQUAL
         LR    R9,R0  COPY REGISTER
         CHI   R9,8  COMPARE OR TEST
         JNL   PSHG  BRANCH IF NOT LOW
         LR    R8,R9  COPY REGISTER
         SLL   R8,2  TIMES 4 FOR INDEX
         LR    R14,R8  COPY REGISTER
         ST    R5,TLS_NODES(R10,R8)  STORE NODE IN SLOT
         LR    R1,R9  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R3  COPY REGISTER
         LR    R9,R1  COPY REGISTER
         AHI   R9,1  COUNT PLUS ONE
         CDS   R0,R8,TLS_OWNER(R10)  COMPARE AND SWAP PAIR
         JE    PSHDONE  BRANCH IF EQUAL
         CLR   R0,R3  COMPARE OR TEST
         JE    PSHUSE  STILL OUR SLOT, RETRY
         J     PSHG  LOST SLOT, DO NOT CLEAR IT
PSHDONE  DS    0H
         STCK  TLS_STAMP(R10)  STAMP LAST USE OF SLOT
         XR    R15,R15  CLEAR REGISTER
         LR    R14,R4  RESTORE RETURN ADDRESS
         BR    R14  RETURN TO CALLER
PSHG     DS    0H
         LARL  R15,PUSHGLOB  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         LR    R14,R4  RESTORE RETURN ADDRESS
         BR    R14  RETURN TO CALLER
*
MPMCQ_PUSHGLOB   DS    0H
PUSHGLOB DS    0H
         LG    R0,QCB_FREE_ABA  LOAD FREELIST HEAD
PUSHH    DS    0H
         L     R3,NODE_CNT_EXT-MPMCQ_NODE(R5)  LOAD NODE GENERATION
         ALFI  R3,1  ADD ONE TO ABA
         ST    R3,NODE_CNT_EXT-MPMCQ_NODE(R5)  STORE NODE GENERATION
         ST    R3,NODE_NEXT_ABA-MPMCQ_NODE(R5)  STORE NEXT ABA TAG
         LR    R1,R0  COPY REGISTER
         ST    R1,NODE_NEXT_PTR-MPMCQ_NODE(R5)  STORE NEXT POINTER
         LG    R8,QCB_FREE_ABA  LOAD FREELIST HEAD
         CGR   R8,R0  COMPARE OR TEST
         JE    PUSHGS  BRANCH IF EQUAL
         LGR   R0,R8  COPY REGISTER
*  COUNT FREELIST PUSH RETRY
         MPMCQ_STATINC R2,QCB_STAT_FREELIST_PUSH_RETRY,R8,R9
         J     PUSHH  BRANCH
PUSHGS   DS    0H
         LR    R1,R0  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R0  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         LR    R9,R5  COPY REGISTER
         CDS   R0,R8,QCB_FREE_ABA  COMPARE AND SWAP PAIR
         JE    PUSHGK  BRANCH IF EQUAL
*  COUNT FREELIST PUSH RETRY
         MPMCQ_STATINC R2,QCB_STAT_FREELIST_PUSH_RETRY,R8,R9
         SLLG  R0,R0,32  SHIFT HALF TO HIGH
         LLGFR R1,R1  KEEP LOW 32 BITS
         ALGR  R0,R1  ADD REGISTERS
         J     PUSHH  BRANCH
PUSHGK   DS    0H
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
*
         END   MPMCQFL
