*PROCESS RENT,MACHINE(Z15)
         TITLE 'MPMCQNT - NOTIFIER'
***********************************************************************
*  MPMCQNT
*  IDENTIFY HAS NO LIST FORM. THE EP NAME IS A CONSTANT AND THE
*  ENTRY ADDRESS IS IN A REGISTER, SO THE STANDARD FORM IS RENT.
*  THIS MACLIB STORAGE HAS NO MF= KEYWORD. OBTAIN AND RELEASE
*  ARE THE PC FORM. LENGTH IS IN R0 AND THE ADDRESS IS IN R1.
*  ATTACHX SF=L IS COPIED BELOW THE LINE, THEN SF=E.
*  THE BELOW-LINE AREA IS 16 BYTES. WORD 0 IS THE USER PARM.
*  MF=(E,(3)) STORES THE QCB ADDRESS THERE. THE CHILD COPIES IT.
*  WORD 1 IS THE TASK ECB. IT STAYS BELOW 16MB. ATTACHX SETS THE
*  HIGH BIT ON THE ECB ADDRESS, AND A 24-BIT POST STILL HITS IT.
*  ECB= MEANS THE SYSTEM DOES NOT REMOVE THE SUBTASK. AFTER THE
*  TASK ECB IS POSTED, DETACH IT. LEAVING IT ATTACHED IS A03.
*  QCBSTOP POSTS THE WAKE ECB, WAITS, THEN DETACHES.
*  EP NAME QNOTIFY IS 7 CHARACTERS.
*  THE NOTIFIER CS-CLEARS THE ECB, THEN READS ENQ_SEQ, AND WAITS
*  ONLY WHEN THE DELTA IS ZERO. PRODUCERS POST AFTER LAAL.
*  THE QCB ADDRESS LIVES AT 0(R13). THE CALLBACK LIST STARTS WITH
*  THE CONTEXT, SO IT CANNOT ALSO HOLD THE QCB.
***********************************************************************
         PRINT GEN
         COPY  REGS
         COPY  DSECTS
         COPY  API
         COPY  ATOMICS
         COPY  LINKAGE
*
MPMCQNT  CSECT
MPMCQNT  AMODE 31
MPMCQNT  RMODE ANY
         USING MPMCQNT,R12
         USING MPMCQ_QCB,R2
*
         ENTRY MPMCQ_NSTART
         ENTRY QCBSTOP
         ENTRY MPMCQ_NOTIF
*
MPMCQ_NSTART DS 0H
         QENTER MPMCQNT
         ST    R2,QCB_TASKPARM QCB ADDRESS FOR THE CHILD
         L     R3,QCB_CB_EP CALLBACK ENTRY
         LTR   R3,R3 ANY CALLBACK
         BNZ   NSWORK YES, START THE TASK
         XR    R15,R15 NO CALLBACK IS SUCCESS
         B     NSRET
NSWORK   LARL  R15,MPMCQ_NOTIF NOTIFIER ENTRY
         OILF  R15,X'80000000' AMODE 31 BIT
         IDENTIFY EP=QNOTIFY,ENTRY=(R15)
         LR    R5,R15 IDENTIFY RETURN CODE
         CHI   R5,0 NEW NAME
         BE    NSATT ATTACH IT
         CHI   R5,4 NAME ALREADY EXISTS
         BNE   NSBAD ANY OTHER CODE FAILS
NSATT    L     R4,4(,R13) CALLER SAVE AREA
         L     R2,28(,R4) QCB BASE AGAIN
         IILF  R0,AT_LEN ATTACH LIST LENGTH
         AHI   R0,7 ROUND UP
         NILF  R0,X'FFFFFFF8' DOUBLEWORD
         STORAGE OBTAIN,LENGTH=(0),ADDR=(1),LOC=BELOW,SP=0
         LR    R10,R1 LIST STORAGE
         ST    R10,0(,R13) REMEMBER IT
         LR    R0,R10 COPY DESTINATION
         IILF  R1,AT_LEN TEMPLATE LENGTH
         LARL  R14,ATTMP TEMPLATE ADDRESS
         LR    R15,R1 SOURCE LENGTH
         MVCL  R0,R14 COPY THE LIST FORM
         LHI   R0,16 PARM WORD PLUS TASK ECB
         STORAGE OBTAIN,LENGTH=(0),ADDR=(1),LOC=BELOW,SP=0
         LR    R3,R1 BELOW-LINE AREA
         XC    0(16,R3),0(R3) CLEAR PARM WORD AND TASK ECB
         L     R4,4(,R13) CALLER SAVE AREA
         L     R2,28(,R4) QCB ADDRESS IN R2
         ST    R3,QCB_STWORK+4 REMEMBER THE AREA
         LA    R8,4(,R3) TASK ECB
         L     R10,0(,R13) ATTACH LIST ADDRESS
         ATTACHX EP=QNOTIFY,ECB=(R8),PARAM=((R2)),VL=1,                X
               MF=(E,(3)),SF=(E,(10))
         LR    R5,R15 ATTACH RETURN CODE
         LR    R7,R1 SUBTASK TCB
         L     R10,0(,R13) LIST TO RELEASE
         L     R4,4(,R13) CALLER SAVE AREA
         L     R2,28(,R4) QCB BASE
         IILF  R0,AT_LEN ATTACH LIST LENGTH
         AHI   R0,7 ROUND UP
         NILF  R0,X'FFFFFFF8' DOUBLEWORD
         LR    R1,R10 RELEASE ADDRESS
         STORAGE RELEASE,LENGTH=(0),ADDR=(1),SP=0
         LTR   R5,R5 ATTACH FAILED
         BNZ   NSBAD YES, FREE THE PARM WORD
         ST    R7,QCB_CB_TCB SAVE THE SUBTASK
         XR    R15,R15 SUCCESS
         B     NSRET
NSBAD    L     R1,QCB_STWORK+4 PARM WORD, IF ANY
         LTR   R1,R1 NOTHING WAS OBTAINED
         BZ    NSBADR
         LHI   R0,16 AREA LENGTH
         STORAGE RELEASE,LENGTH=(0),ADDR=(1),SP=0
NSBADR   LR    R15,R5 RETURN THE FAILURE CODE
NSRET    QLEAVE
*
QCBSTOP  QLEAF MPMCQNT
         L     R2,QSTOP_QCB-MPMCQ_STOP_PL(R11)
         L     R0,QCB_FLAGS
QSTOPLP  LR    R3,R0
         OILF  R3,QCBF_STOP
         CS    R0,R3,QCB_FLAGS
         BNE   QSTOPLP
         POST  QCB_CB_ECB WAKE THE NOTIFIER
         L     R0,QCB_CB_TCB SUBTASK, IF ATTACHED
         LTR   R0,R0 NO NOTIFIER
         BZ    QSTRET
         L     R1,QCB_STWORK+4 BELOW-LINE AREA
         LA    R1,4(,R1) TASK ECB
         LHI   R0,1 ONE EVENT
         SVC   1 WAIT FOR TASK END
         DETACH QCB_CB_TCB REMOVE THE ENDED SUBTASK
         XC    QCB_CB_TCB,QCB_CB_TCB TCB IS GONE
         L     R1,QCB_STWORK+4 AREA TO RELEASE
         LHI   R0,16 AREA LENGTH
         STORAGE RELEASE,LENGTH=(0),ADDR=(1),SP=0
QSTRET   XR    R15,R15
         QLEAVER
*
MPMCQ_NOTIF DS 0H
         QENTER MPMCQNT
         L     R2,0(R11) QCB ADDRESS FROM THE PARM WORD
         NILF  R2,X'7FFFFFFF' DROP THE VL BIT
         ST    R2,0(,R13) KEEP IT ACROSS OBTAIN
         LHI   R0,32 CALLBACK LIST LENGTH
         STORAGE OBTAIN,LENGTH=(0),ADDR=(1),LOC=ANY,SP=0
         LR    R10,R1 CALLBACK LIST
         L     R2,0(,R13) QCB BASE
NLOOP    L     R2,0(,R13) QCB SURVIVES THE CALLBACK
         L     R0,QCB_FLAGS
         NILF  R0,QCBF_STOP STOP BIT ONLY
         LTR   R0,R0 STOP REQUESTED
         BNZ   NDONE YES
         L     R0,QCB_CB_ECB
NCLR     XR    R1,R1 CLEAR VALUE
         CS    R0,R1,QCB_CB_ECB
         JNE   NCLR RETRY THE CLEAR
         L     R0,QCB_FLAGS
         NILF  R0,QCBF_STOP STOP BIT ONLY
         LTR   R0,R0 STOP WON THE RACE
         BNZ   NDONE YES
         L     R6,QCB_ENQ_SEQ
         L     R5,QCB_CB_SEQ_SEEN
         LR    R4,R6
         SR    R4,R5 PENDING COUNT
         LTR   R4,R4 NOTHING NEW
         BNZ   NWORK WORK IS WAITING
         WAIT  ECB=QCB_CB_ECB
         J     NLOOP
NWORK    L     R6,QCB_ENQ_SEQ
         L     R5,QCB_CB_SEQ_SEEN
         LR    R4,R6
         SR    R4,R5 PENDING COUNT
         LTR   R4,R4 CLEARED WHILE WE LOOKED
         JZ    NLOOP YES, WAIT AGAIN
         ST    R6,QCB_CB_SEQ_SEEN REMEMBER THIS SEQUENCE
         MPMCQ_STATINC R2,QCB_STAT_CB_CALLS,R8,R9
         MPMCQ_STATMAX R2,QCB_STAT_CB_PENDING_MAX,R4,R8,R0
         L     R7,QCB_CB_EP CALLBACK ENTRY
         LTR   R7,R7 STILL SET
         BZ    NLOOP NO, WAIT AGAIN
         LR    R1,R10 CALLBACK LIST
         L     R0,QCB_CB_CTX
         ST    R0,CBP_CTX-MPMCQ_CB_PLIST(R1)
         ST    R2,CBP_QCB-MPMCQ_CB_PLIST(R1)
         ST    R4,CBP_PENDING-MPMCQ_CB_PLIST(R1)
         BALR  R14,R7 CALL THE USER
         B     NLOOP
NDONE    LR    R6,R10 AREA TO RELEASE
         LHI   R0,32 RELEASE LENGTH
         LR    R1,R6 RELEASE ADDRESS
         STORAGE RELEASE,LENGTH=(0),ADDR=(1),SP=0
         XR    R15,R15
         QLEAVE
*
         LTORG
         DS    0D
ATTMP    ATTACHX EP=QNOTIFY,SF=L
AT_LEN   EQU   *-ATTMP
         END   MPMCQNT
