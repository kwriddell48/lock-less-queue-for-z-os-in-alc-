*PROCESS RENT,MACHINE(Z15)
         TITLE 'MPMCQST - QSTATS'
***********************************************************************
*  MPMCQST
*  QSTATS(QCB,OUT,OUTLEN). LENGTH COMPARE IS UNSIGNED (CLR).
*  SNAPSHOT IS BEST-EFFORT. NO LOCK IS TAKEN.
***********************************************************************
         PRINT GEN
         COPY  REGS
         COPY  DSECTS
         COPY  API
         COPY  LINKAGE
*
MPMCQST  CSECT
MPMCQST  AMODE 31
MPMCQST  RMODE ANY
         USING MPMCQST,R12
         USING MPMCQ_QCB,R2
         USING MPMCQ_STATS,R3
*
         ENTRY QSTATS
*
QSTATS   QLEAF MPMCQST  SAVE REGS AND SET BASE
         L     R2,QST_QCBADDR-MPMCQ_QSTATS_PLIST(R11)  LOAD QCB ADDRESS
*  LOAD STATS BUFFER
         L     R3,QST_OUTADDR-MPMCQ_QSTATS_PLIST(R11)
*  LOAD OUTLEN ADDRESS
         L     R4,QST_OUTLEN-MPMCQ_QSTATS_PLIST(R11)
         LTR   R2,R2  COMPARE OR TEST
         BZ    QSTDONE  BRANCH IF ZERO
         LTR   R3,R3  COMPARE OR TEST
         BZ    QSTDONE  BRANCH IF ZERO
         LHI   R5,STATS_END-MPMCQ_STATS  STATS VERSION
         CLR   R4,R5  COMPARE OR TEST
         BNH   QSTLEN  BRANCH IF NOT HIGH
         LR    R4,R5  COPY REGISTER
QSTLEN   LHI   R0,MPMCQ_STATS_VERSION  STATS VERSION
         ST    R0,STATS_VERSION  STORE HEADER FIELD
         ST    R4,STATS_SIZE  STORE STATS FIELD
         L     R0,QCB_STAT_ENQ_OK  COPY ONE STATS WORD
         ST    R0,STATS_ENQ_OK  STORE STATS FIELD
         L     R0,QCB_STAT_DEQ_OK  COPY ONE STATS WORD
         ST    R0,STATS_DEQ_OK  STORE STATS FIELD
         L     R0,QCB_STAT_DEQ_EMPTY  COPY ONE STATS WORD
         ST    R0,STATS_DEQ_EMPTY  STORE STATS FIELD
         L     R0,QCB_STAT_ENQ_ALLOC_FAIL  COPY ONE STATS WORD
         ST    R0,STATS_ENQ_ALLOC_FAIL  STORE STATS FIELD
         L     R0,QCB_STAT_ENQ_RETRY  COPY ONE STATS WORD
         ST    R0,STATS_ENQ_RETRY  STORE STATS FIELD
         L     R0,QCB_STAT_DEQ_RETRY  COPY ONE STATS WORD
         ST    R0,STATS_DEQ_RETRY  STORE STATS FIELD
         L     R0,QCB_STAT_FREELIST_POP_RETRY  COPY ONE STATS WORD
         ST    R0,STATS_FREELIST_POP_RETRY  STORE STATS FIELD
         L     R0,QCB_STAT_FREELIST_PUSH_RETRY  COPY ONE STATS WORD
         ST    R0,STATS_FREELIST_PUSH_RETRY  STORE STATS FIELD
         L     R0,QCB_STAT_QDEPTH_CUR  COPY ONE STATS WORD
         ST    R0,STATS_QDEPTH_CUR  STORE STATS FIELD
         L     R0,QCB_STAT_QDEPTH_MAX  COPY ONE STATS WORD
         ST    R0,STATS_QDEPTH_MAX  STORE STATS FIELD
         L     R0,QCB_STAT_PAYLOAD64_CUR_HI  COPY ONE STATS WORD
         ST    R0,STATS_PAYLOAD64_CUR  STORE STATS FIELD
         L     R0,QCB_STAT_PAYLOAD64_CUR_LO  COPY ONE STATS WORD
         ST    R0,STATS_PAYLOAD64_CUR+4  STORE STATS FIELD
         L     R0,QCB_STAT_PAYLOAD64_MAX_HI  COPY ONE STATS WORD
         ST    R0,STATS_PAYLOAD64_MAX  STORE STATS FIELD
         L     R0,QCB_STAT_PAYLOAD64_MAX_LO  COPY ONE STATS WORD
         ST    R0,STATS_PAYLOAD64_MAX+4  STORE STATS FIELD
         L     R0,QCB_STAT_POST_INTERNAL  COPY ONE STATS WORD
         ST    R0,STATS_POST_INTERNAL  STORE STATS FIELD
         L     R0,QCB_STAT_POST_USERECB  COPY ONE STATS WORD
         ST    R0,STATS_POST_USERECB  STORE STATS FIELD
         L     R0,QCB_STAT_CB_CALLS  COPY ONE STATS WORD
         ST    R0,STATS_CB_CALLS  STORE STATS FIELD
         L     R0,QCB_STAT_CB_PENDING_MAX  COPY ONE STATS WORD
         ST    R0,STATS_CB_PENDING_MAX  STORE STATS FIELD
QSTDONE  XR    R15,R15  CLEAR REGISTER
         QLEAVER  RESTORE REGS AND RETURN
*
         END   MPMCQST
