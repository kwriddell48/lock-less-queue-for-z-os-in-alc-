*PROCESS RENT,MACHINE(Z15)
         TITLE 'MPMCQSTO - PAYLOAD STORAGE'
***********************************************************************
*  MPMCQSTO
*  PAYGET: R2=QCB, R7=LEN. R15=0 AND R8/R9=ADDR HALVES, OR R15=8.
*  HALVES ARE IN BITS 32-63. QLEAVER89 LEAVES THEM THERE.
*  PAYFREE: R2=QCB, R7=LEN, R1->8-BYTE ADDRESS IN THE NODE.
*  LEN 1..PAY31_MAX USES A 31-BIT SIZE-CLASS FREELIST.
*  ABOVE THAT, IARV64 GETSTOR/DETACH (1MB SEGMENTS).
*  SLABS ARE NEVER FREEMAIN'D. THE OBTAINING TASK MUST OUTLIVE THEM.
*  CALLER POINTS R13 AT A PRIVATE 72-BYTE SAVE AREA. STM USES IT.
*  THE 64-BIT ADDRESS IS LOADED FROM THE NODE AFTER GETMAIN.
***********************************************************************
         PRINT GEN
         COPY  REGS
         COPY  DSECTS
         COPY  API
         COPY  LINKAGE
*
MPMCQSTO CSECT
MPMCQSTO AMODE 31
MPMCQSTO RMODE ANY
         USING MPMCQ_QCB,R2
*
         ENTRY MPMCQ_PAYGET
         ENTRY MPMCQ_PAYFREE
*
MPMCQ_PAYGET     DS    0H
         STM   R14,R12,12(R13)  SAVE CALLER REGISTERS
         LARL  R12,MPMCQ_PAYGET  LOAD RELATIVE ADDRESS
         USING MPMCQ_PAYGET,R12
         LR    R11,R1  COPY REGISTER
         LTR   R7,R7  COMPARE OR TEST
         JZ    PAYZ  BRANCH IF ZERO
         CLFI  R7,PAY31_MAX  COMPARE OR TEST
         JH    PAY64  BRANCH IF HIGH
         LARL  R15,CLASIFY  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         SLL   R3,3  TIMES 4 FOR INDEX
*  ADDRESS SIZE-CLASS HEAD
         LA    R4,QCB_POOL-MPMCQ_QCB(R3,R2)  ADDRESS SIZE-CLASS HEAD
         LR    R6,R15  COPY REGISTER
         LARL  R15,POOLPOP  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         LTR   R1,R1  COMPARE OR TEST
         JNZ   PAYGOT  BRANCH IF NOT ZERO
         LR    R0,R6  COPY REGISTER
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R9,R1  COPY REGISTER
         XR    R8,R8  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         J     PAYRET  BRANCH
PAYGOT   DS    0H
         LR    R9,R1  COPY REGISTER
         XR    R8,R8  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         J     PAYRET  BRANCH
PAYZ     DS    0H
         XR    R8,R8  CLEAR REGISTER
         XR    R9,R9  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         J     PAYRET  BRANCH
PAY64    DS    0H
         IILF  R0,GET64_TLEN  LOAD IMMEDIATE
         AHI   R0,7  ROUND UP
         NILF  R0,X'FFFFFFF8'  ROUND LENGTH TO 8
         LR    R6,R0  COPY REGISTER
         AHI   R0,16  COUNT PLUS ONE
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R10,R1  COPY REGISTER
         ST    R10,0(R13)  KEEP PLIST POINTER
         LR    R0,R10  COPY REGISTER
         LR    R1,R6  COPY REGISTER
         LARL  R14,GET64T  LOAD RELATIVE ADDRESS
         LR    R15,R6  COPY REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         LA    R3,0(R6,R10)  FORM AN ADDRESS
         XR    R4,R4  CLEAR REGISTER
         LR    R5,R7  COPY REGISTER
         IILF  R2,X'000FFFFF'  ROUND UP TO 1MB
         ALR   R5,R2  ADD REGISTERS
         SRL   R5,20  SHIFT TCB FOR HASH
         ST    R4,0(R3)  STORE FULLWORD
         ST    R5,4(R3)  CHAIN SAVE AREA
         LA    R4,8(R3)  FORM AN ADDRESS
         L     R1,0(R13)  RELOAD SAVED PLIST
*  OBTAIN 64-BIT STORAGE
         IARV64 REQUEST=GETSTOR,COND=YES,SEGMENTS=(R3),                X
               ORIGIN=(R4),FPROT=NO,PLISTVER=MAX,MF=(E,(R1))
         LR    R5,R15  COPY REGISTER
         LG    R8,8(R3)  LOAD DOUBLEWORD
         LGR   R9,R8  COPY REGISTER
         SRLG  R8,R8,32  SHIFT ABA TO LOW HALF
         L     R10,0(R13)  RELOAD SAVED PLIST
         IILF  R0,GET64_TLEN  LOAD IMMEDIATE
         AHI   R0,7  ROUND UP
         NILF  R0,X'FFFFFFF8'  ROUND LENGTH TO 8
         AHI   R0,16  COUNT PLUS ONE
         LR    R1,R10  COPY REGISTER
         FREEMAIN R,LV=(0),A=(1)  RELEASE WORK AREA
         LTR   R5,R5  COMPARE OR TEST
         JZ    PAYOK  BRANCH IF ZERO
         XR    R8,R8  CLEAR REGISTER
         XR    R9,R9  CLEAR REGISTER
         LHI   R15,8  RETURN CODE 8
         J     PAYRET  BRANCH
PAYOK    DS    0H
         XR    R15,R15  CLEAR REGISTER
PAYRET   DS    0H
         QLEAVER89  RETURN RC AND ADDR HALVES
         DROP  R12
*
MPMCQ_PAYFREE    DS    0H
         STM   R14,R12,12(R13)  SAVE CALLER REGISTERS
         LARL  R12,MPMCQ_PAYFREE  LOAD RELATIVE ADDRESS
         USING MPMCQ_PAYFREE,R12
         LR    R11,R1  COPY REGISTER
         LTR   R7,R7  COMPARE OR TEST
         JZ    FRERET  BRANCH IF ZERO
         CLFI  R7,PAY31_MAX  COMPARE OR TEST
         JH    FRE64  BRANCH IF HIGH
         LG    R8,0(R11)  LOAD DOUBLEWORD
         LLGFR R5,R8  KEEP LOW 32 BITS
         LARL  R15,CLASIFY  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         SLL   R3,3  TIMES 4 FOR INDEX
*  ADDRESS SIZE-CLASS HEAD
         LA    R4,QCB_POOL-MPMCQ_QCB(R3,R2)  ADDRESS SIZE-CLASS HEAD
         LARL  R15,POOLPSH  LOAD RELATIVE ADDRESS
         BALR  R14,R15  CALL AND SET RETURN
         J     FRERET  BRANCH
FRE64    DS    0H
         IILF  R0,FREE64_TLEN  LOAD IMMEDIATE
         AHI   R0,7  ROUND UP
         NILF  R0,X'FFFFFFF8'  ROUND LENGTH TO 8
         LR    R6,R0  COPY REGISTER
         AHI   R0,8  ADD PARM WORD
         GETMAIN R,LV=(0)  OBTAIN STORAGE
         LR    R10,R1  COPY REGISTER
         ST    R10,0(R13)  KEEP PLIST POINTER
         LR    R0,R10  COPY REGISTER
         LR    R1,R6  COPY REGISTER
         LARL  R14,FREE64T  LOAD RELATIVE ADDRESS
         LR    R15,R6  COPY REGISTER
         MVCL  R0,R14  MOVE OR CLEAR BYTES
         LA    R3,0(R6,R10)  FORM AN ADDRESS
         LG    R8,0(R11)  LOAD DOUBLEWORD
         STG   R8,0(R3)  STORE 64-BIT ORIGIN  STORE DOUBLEWORD
         L     R1,0(R13)  RELOAD SAVED PLIST
*  DETACH 64-BIT OBJECT
         IARV64 REQUEST=DETACH,COND=YES,MEMOBJSTART=(R3),              X
               PLISTVER=MAX,MF=(E,(R1))
         L     R10,0(R13)  RELOAD SAVED PLIST
         IILF  R0,FREE64_TLEN  LOAD IMMEDIATE
         AHI   R0,7  ROUND UP
         NILF  R0,X'FFFFFFF8'  ROUND LENGTH TO 8
         AHI   R0,8  ADD PARM WORD
         LR    R1,R10  COPY REGISTER
         FREEMAIN R,LV=(0),A=(1)  RELEASE WORK AREA
FRERET   DS    0H
         XR    R15,R15  CLEAR REGISTER
         QLEAVER  RESTORE REGS AND RETURN
         DROP  R12
*
* R7=LEN. R3=CLASS INDEX. R15=SLAB BYTES. PRESERVES R2,R4-R13.
CLASIFY  DS    0H
         CLFI  R7,POOL_2K  COMPARE OR TEST
         JNH   CL0  BRANCH IF NOT HIGH
         CLFI  R7,POOL_4K  COMPARE OR TEST
         JNH   CL1  BRANCH IF NOT HIGH
         CLFI  R7,POOL_8K  COMPARE OR TEST
         JNH   CL2  BRANCH IF NOT HIGH
         CLFI  R7,POOL_16K  COMPARE OR TEST
         JNH   CL3  BRANCH IF NOT HIGH
         CLFI  R7,POOL_32K  COMPARE OR TEST
         JNH   CL4  BRANCH IF NOT HIGH
         LHI   R3,5  LOAD HALFWORD
         IILF  R15,65536  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
CL0      DS    0H
         LHI   R3,0  LOAD HALFWORD
         IILF  R15,2048  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
CL1      DS    0H
         LHI   R3,1  PLUS ONE
         IILF  R15,4096  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
CL2      DS    0H
         LHI   R3,2  LOAD HALFWORD
         IILF  R15,8192  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
CL3      DS    0H
         LHI   R3,3  LOAD HALFWORD
         IILF  R15,16384  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
CL4      DS    0H
         LHI   R3,4  LOAD HALFWORD
         IILF  R15,32768  LOAD IMMEDIATE
         BR    R14  RETURN TO CALLER
*
* R4->FREELIST DOUBLEWORD. R1=SLAB OR 0. PRESERVES R4,R6,R7,R10-R13.
* THE NEXT WORD IS LOADED, THEN THE HEAD IS REREAD. A CHANGED HEAD
* RETRIES. THE CDS IS NOT ATTEMPTED ON THAT STALE NEXT POINTER.
* THE LINK ABA IN THE SLAB IS NOT THE FREELIST TAG. POP BUILDS THE
* NEW HEAD TAG FROM THE OBSERVED HEAD TAG PLUS ONE.
POOLPOP  DS    0H
         LG    R0,0(R4)  LOAD DOUBLEWORD
POOLPH   DS    0H
         LR    R1,R0  COPY REGISTER
         LTR   R1,R1  COMPARE OR TEST
         JZ    POOLPE  BRANCH IF ZERO
         L     R8,4(R1)  LOAD NEXT SLAB POINTER
         LG    R3,0(R4)  LOAD DOUBLEWORD
         CGR   R3,R0  COMPARE OR TEST
         JE    POOLPS  BRANCH IF EQUAL
         LGR   R0,R3  COPY REGISTER
         J     POOLPH  BRANCH
POOLPS   DS    0H
         LR    R9,R8  COPY REGISTER
         LR    R3,R1  COPY REGISTER
         LR    R1,R0  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R0  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         CDS   R0,R8,0(R4)  COMPARE AND SWAP PAIR
         JE    POOLPK  BRANCH IF EQUAL
         SLLG  R0,R0,32  SHIFT HALF TO HIGH
         LLGFR R1,R1  KEEP LOW 32 BITS
         ALGR  R0,R1  ADD REGISTERS
         J     POOLPH  BRANCH
POOLPK   DS    0H
         LR    R1,R3  COPY REGISTER
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
POOLPE   DS    0H
         XR    R1,R1  CLEAR REGISTER
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
*
* R4->FREELIST, R5=SLAB. PRESERVES R4,R5,R6,R7,R10-R13.
* 0(R5) IS NOT USED AS A TAG. THE HEAD ABA COMES FROM THE HEAD.
POOLPSH  DS    0H
         LG    R0,0(R4)  LOAD DOUBLEWORD
POOLSH   DS    0H
         XR    R3,R3  CLEAR REGISTER
         ST    R3,0(R5)  STORE FULLWORD
         LR    R1,R0  COPY REGISTER
         ST    R1,4(R5)  STORE NEXT SLAB POINTER
         LG    R8,0(R4)  LOAD DOUBLEWORD
         CGR   R8,R0  COMPARE OR TEST
         JE    POOLSS  BRANCH IF EQUAL
         LGR   R0,R8  COPY REGISTER
         J     POOLSH  BRANCH
POOLSS   DS    0H
         LR    R1,R0  COPY REGISTER
         SRLG  R0,R0,32  SHIFT ABA TO LOW HALF
         LR    R8,R0  COPY REGISTER
         ALFI  R8,1  ADD ONE TO ABA
         LR    R9,R5  COPY REGISTER
         CDS   R0,R8,0(R4)  COMPARE AND SWAP PAIR
         JE    POOLSK  BRANCH IF EQUAL
         SLLG  R0,R0,32  SHIFT HALF TO HIGH
         LLGFR R1,R1  KEEP LOW 32 BITS
         ALGR  R0,R1  ADD REGISTERS
         J     POOLSH  BRANCH
POOLSK   DS    0H
         XR    R15,R15  CLEAR REGISTER
         BR    R14  RETURN TO CALLER
*
         LTORG
         DS    0D
         IARV64 MF=(L,GET64T,0D),PLISTVER=MAX  64-BIT STORAGE REQUEST
GET64_TLEN EQU *-GET64T
         DS    0D
         IARV64 MF=(L,FREE64T,0D),PLISTVER=MAX  64-BIT STORAGE REQUEST
FREE64_TLEN EQU *-FREE64T
         END   MPMCQSTO
